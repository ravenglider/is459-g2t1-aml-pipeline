"""Render the published sample handoff from the maintained production SQL."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def build_queries():
    outputs = {}
    mapping = {
        'bq2_lift.sql': '03_lift.sql',
        'tradeoff.sql': '04_tradeoff.sql',
        'sankey.sql': '05_sankey.sql',
        'frequency.sql': '02_frequency.sql',
        'validation.sql': '01_validation.sql',
    }
    for source, target in mapping.items():
        sql = (ROOT / source).read_text()
        sql = sql.replace('is459_g2t1_aml.bq2_sequences', 'is459_g2t1_aml.bq2_sequences_dev')
        for name in ('bq2_lift', 'bq2_tradeoff', 'bq2_sankey'):
            sql = sql.replace('is459_g2t1_aml.' + name, 'is459_g2t1_aml.' + name + '_dev')
            sql = sql.replace('/' + name + "/'", '/' + name + "_dev/sample_20220901/'")
        sql = sql.replace("dataset IN ('HI-Medium', 'LI-Medium')", "dataset = 'sample'")
        sql = sql.replace("dataset = 'HI-Medium'", "dataset = 'sample'")
        sql = sql.replace("s.dataset = 'sample'", "s.dataset = 'sample' AND s.start_date = '2022-09-01'")
        # Only unaliased sequence scans get a start-date predicate; clean stays complete.
        sql = sql.replace("FROM is459_g2t1_aml.bq2_sequences_dev\nWHERE dataset = 'sample'",
                          "FROM is459_g2t1_aml.bq2_sequences_dev\nWHERE dataset = 'sample' AND start_date = '2022-09-01'")
        sql = sql.replace("FROM is459_g2t1_aml.bq2_sequences_dev\n  WHERE dataset = 'sample'",
                          "FROM is459_g2t1_aml.bq2_sequences_dev\n  WHERE dataset = 'sample' AND start_date = '2022-09-01'")
        sql = sql.replace('-- Frozen HI rules, evaluated separately by length/support policy on HI and LI.',
                          '-- Sample in-sample arithmetic test only; no HI-to-LI evaluation.')
        sql = sql.replace('-- Inspect frequencies without outcomes before choosing the primary support cutoff.',
                          '-- Sample frequencies for integration testing, not selection of the final HI cutoff.')
        header = '-- GENERATED by prepare_development.py; edit the production source, then regenerate.\n-- SAMPLE INTEGRATION ONLY. Not final HI/LI findings.\n'
        if source == 'validation.sql':
            before, after = sql.split('-- POST-CTAS only:', 1)
            outputs['06_reconciliation.sql'] = header + '-- POST-CTAS only:' + after
            sql = before.replace('-- Run preflight statements before lineage joins. Expect both datasets, valid v1 rows,',
                                 '-- Run preflight statements before lineage joins. Expect sample, valid v1 rows,')
        if "'HI-Medium'" in sql or "'LI-Medium'" in sql:
            raise ValueError('Unmapped production dataset in ' + source)
        outputs[target] = header + sql.rstrip() + "\n"
    return outputs


if __name__ == '__main__':
    destination = ROOT / 'development'
    destination.mkdir(exist_ok=True)
    for name, sql in build_queries().items():
        (destination / name).write_text(sql)
